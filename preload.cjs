const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('assist', {
  floatingStatus: () => ipcRenderer.invoke('window:floating-status'),
  setFloating: (enabled) => ipcRenderer.invoke('window:set-floating', enabled),
  startChannel: (id, source) => ipcRenderer.invoke('asr:start', { id, source }),
  stopChannel: (id) => ipcRenderer.invoke('asr:stop', id),
  sendAudio: (id, pcm) => ipcRenderer.send('asr:audio', id, pcm),
  fixRoute: () => ipcRenderer.invoke('route:fix'),
  openSound: () => ipcRenderer.send('sound:open'),
  openMidi: () => ipcRenderer.send('midi:open'),
  retryCredentials: () => ipcRenderer.invoke('ark:retry'),
  arkStatus: () => ipcRenderer.invoke('ark:status'),
  models: () => ipcRenderer.invoke('ark:models'),
  setModel: (model) => ipcRenderer.invoke('ark:set-model', model),
  getProfile: () => ipcRenderer.invoke('ark:get-profile'),
  setProfile: (text) => ipcRenderer.invoke('ark:set-profile', text),
  getJd: () => ipcRenderer.invoke('ark:get-jd'),
  setJd: (text) => ipcRenderer.invoke('ark:set-jd', text),
  summarizeContext: (payload) => ipcRenderer.invoke('llm:summarize-context', payload),
  ask: (payload) => ipcRenderer.invoke('llm:ask', payload),
  cancelAsk: (askId) => ipcRenderer.send('llm:cancel', askId),
  onLlmDelta: (cb) => ipcRenderer.on('llm:delta', (_e, payload) => cb(payload)),
  onHotkey: (cb) => ipcRenderer.on('hotkey', (_e, action) => cb(action)),
  onPhoneCmd: (cb) => ipcRenderer.on('phone-cmd', (_e, action) => cb(action)), // 手机端「开始/结束面试」转发
  onText: (cb) => ipcRenderer.on('asr:text', (_e, payload) => cb(payload)),
  phoneSync: (payload) => ipcRenderer.send('phone:sync', payload),
  showQr: () => ipcRenderer.send('phone:show-qr'),
  openRecords: () => ipcRenderer.send('record:open'),
  recordList: () => ipcRenderer.invoke('record:list'),
  recordRead: (file) => ipcRenderer.invoke('record:read', file),
  recordFlush: (entries) => ipcRenderer.send('record:flush', entries),
  sessionStart: () => ipcRenderer.invoke('session:start'),
  sessionEnd: () => ipcRenderer.invoke('session:end'),
});
